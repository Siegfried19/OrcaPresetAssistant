const catalogs = { 'zh-CN': zhCN, en } as const

export type TranslationKey = MessageKey
export type TranslationValues = Readonly<Record<string, string | number>>
export type Translator = (key: TranslationKey, values?: TranslationValues) => string

export function createTranslator(language: keyof typeof catalogs): Translator {
  return (key, values = {}) =>
    Object.entries(values).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      catalogs[language][key] as string,
    )
}

export const errorTranslationKey = (code: AppErrorCode): TranslationKey => `error.${code}`
export const warningTranslationKey = (warning: DashboardWarning): TranslationKey =>
  `warning.${warning}`
export const validationTranslationKey = (issue: ValidationIssue): TranslationKey =>
  `validation.${issue}`
export const materialRoleTranslationKey = (role: RecordedMaterialRole): TranslationKey =>
  `materialRole.${role}`
